def norm_pri(p):
    p = re.sub(r'\*\*|\(|\)', '', str(p)).strip()
    for k in ['Must', 'Should', 'Could', "Won't", 'TBD']:
        if p.startswith(k): return k
    if '不要' in p or '対象外' in p: return '不要'
    if '外部待ち' in p: return 'TBD'
    if p.startswith('D') or p == '—' or p == '': return '推奨値あり'
    return 'TBD'

