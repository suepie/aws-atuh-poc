def explode(sheet, effcol, table, namecol, ratio_of):
    out, n_new = [], 0
    for r in D[sheet]:
        spec = table.get(r['ID'])
        if not spec or num(r[effcol]) == 0:
            out.append(r); continue
        assert abs(sum(s[1] for s in spec) - num(r[effcol])) < 1e-9, (r['ID'], sum(s[1] for s in spec), r[effcol])
        ratio = (num(r[ratio_of]) / num(r[effcol])) if num(r[effcol]) else 0
        for i, (nm, eff, done) in enumerate(spec, 1):
            c = dict(r); c['ID'] = f"{r['ID']}-{i}"; c[namecol] = nm; c[effcol] = fmt(eff)
            c[ratio_of] = fmt(eff * ratio)
            if done and '概要・完了定義' in c: c['概要・完了定義'] = done
            out.append(c); n_new += 1
        n_new -= 1
    D[sheet] = out; return n_new

